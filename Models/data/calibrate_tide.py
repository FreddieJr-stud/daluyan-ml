# Constituent names in fixed order for optimization
CONSTITUENT_NAMES = ["M2", "S2", "K1", "O1", "P1", "N2", "K2", "Q1"]


def _predict_with_params(
    dt_pht: datetime,
    amplitudes: np.ndarray,
    phases: np.ndarray,
    msl: float,
) -> float:
    """Predict tide height using given parameters (same math as tide.py)."""
    # Convert PHT to UTC
    dt_utc = dt_pht - timedelta(hours=8)
    astro = _astronomical_arguments(dt_utc)

    tide = msl
    for i, name in enumerate(CONSTITUENT_NAMES):
        c = MANILA_CONSTITUENTS[name]
        V0 = _equilibrium_argument(c["doodson"], astro)
        f, u = _node_factor(name, astro["N"])
        angle_deg = V0 + u - phases[i]
        tide += f * amplitudes[i] * math.cos(math.radians(angle_deg))

    return tide


def _objective(params: np.ndarray, ref_data: list) -> float:
    """RMSE between predicted and reference heights."""
    amplitudes = params[:8]
    phases = params[8:16]
    msl = params[16]

    errors_sq = []
    for year, month, day, hour, minute, ref_h in ref_data:
        dt = datetime(year, month, day, hour, minute)
        pred = _predict_with_params(dt, amplitudes, phases, msl)
        errors_sq.append((pred - ref_h) ** 2)

    return math.sqrt(sum(errors_sq) / len(errors_sq))


